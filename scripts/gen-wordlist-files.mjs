// Generates the English wordlist module and public download files from the
// pinned upstream copy in data/upstream/english.txt, after verifying its hash.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const EXPECTED_SHA256 = '2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda';
const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

const raw = readFileSync('data/upstream/english.txt');
if (sha256(raw) !== EXPECTED_SHA256) throw new Error('english.txt hash mismatch');
const words = raw.toString('utf8').trim().split('\n');
if (words.length !== 2048) throw new Error(`expected 2048 words, got ${words.length}`);

const txt = words.join('\n') + '\n';
const json = JSON.stringify(words, null, 2) + '\n';
const csv = 'index,index_1_based,binary,word\n' +
  words.map((w, i) => `${i},${i + 1},${i.toString(2).padStart(11, '0')},${w}`).join('\n') + '\n';

mkdirSync('public/wordlist', { recursive: true });
const files = { 'english.txt': txt, 'english.json': json, 'english.csv': csv };
const hashes = {};
for (const [name, body] of Object.entries(files)) {
  writeFileSync(`public/wordlist/${name}`, body);
  hashes[name] = { sha256: sha256(body), bytes: Buffer.byteLength(body) };
}

writeFileSync('src/data/wordlist-english.ts',
  '// Generated by scripts/gen-wordlist-files.mjs from data/upstream/english.txt. Do not edit.\n' +
  `export const UPSTREAM_SHA256 = '${EXPECTED_SHA256}';\n` +
  `export const DOWNLOADS = ${JSON.stringify(hashes, null, 2)} as const;\n` +
  `export const WORDLIST: readonly string[] = ${JSON.stringify(words)};\n`);
console.log('wordlist files generated', hashes);

// Official English test vectors (trezor/python-mnemonic vectors.json), passphrase "TREZOR".
const VECTORS_SHA256 = 'fa3b937b7cff9c9b8ecd3aa011faeb8d6dd67993174b72326e83f4de8fdb30f8';
const vraw = readFileSync('data/upstream/vectors.json');
if (sha256(vraw) !== VECTORS_SHA256) throw new Error('vectors.json hash mismatch');
const english = JSON.parse(vraw.toString('utf8')).english
  .map(([entropy, mnemonic, seed], i) => ({ id: i + 1, entropy, mnemonic, seed }));
writeFileSync('src/data/vectors.ts',
  '// Generated by scripts/gen-wordlist-files.mjs from data/upstream/vectors.json. Do not edit.\n' +
  "export const VECTOR_PASSPHRASE = 'TREZOR';\n" +
  `export const VECTORS_SHA256 = '${VECTORS_SHA256}';\n` +
  'export interface TestVector { id: number; entropy: string; mnemonic: string; seed: string }\n' +
  `export const VECTORS: readonly TestVector[] = ${JSON.stringify(english, null, 2)};\n`);
console.log(`vectors generated: ${english.length}`);
